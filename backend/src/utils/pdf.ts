import PDFDocument from 'pdfkit';

interface PrescriptionPdfData {
  prescriptionNumber: string;
  createdAt: Date;
  diagnosis: string;
  notes?: string | null;
  followUpDate?: string | null;
  doctor: { name: string; qualification: string; registrationNumber: string; specialty?: string | null };
  patient: { name: string; age?: number | null; gender?: string | null; phone?: string | null };
  items: Array<{ medicineName: string; dosage: string; frequency: string; duration: string; instructions?: string | null }>;
  appointment: { number: string; date: string };
}

function drawHeader(doc: PDFKit.PDFDocument, title: string, subtitle: string): void {
  doc.rect(0, 0, doc.page.width, 92).fill('#0B5FFF');
  doc.fillColor('#FFFFFF').fontSize(22).font('Helvetica-Bold').text('MediBook', 48, 28);
  doc.fontSize(9).font('Helvetica').fillColor('#DCE9FF').text(subtitle, 48, 58);
  doc.fontSize(16).font('Helvetica-Bold').fillColor('#FFFFFF').text(title, 0, 32, { align: 'right', width: doc.page.width - 48 });
  doc.fillColor('#0F172A');
  doc.moveDown(3);
}

function labelValue(doc: PDFKit.PDFDocument, x: number, y: number, label: string, value: string): void {
  doc.fontSize(8).fillColor('#64748B').font('Helvetica-Bold').text(label.toUpperCase(), x, y);
  doc.fontSize(11).fillColor('#0F172A').font('Helvetica').text(value, x, y + 13, { width: 220 });
}

function toBuffer(doc: PDFKit.PDFDocument): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.end();
  });
}

export async function renderPrescriptionPdf(data: PrescriptionPdfData): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'A4', margin: 48, info: { Title: `Prescription ${data.prescriptionNumber}` } });
  drawHeader(doc, 'PRESCRIPTION', `Rx ID: ${data.prescriptionNumber}`);

  doc.y = 120;
  labelValue(doc, 48, 120, 'Doctor', `Dr. ${data.doctor.name}`);
  labelValue(doc, 48, 160, 'Qualification', data.doctor.qualification);
  labelValue(doc, 300, 120, 'Registration', data.doctor.registrationNumber);
  labelValue(doc, 300, 160, 'Specialty', data.doctor.specialty ?? 'General Medicine');

  doc.moveTo(48, 218).lineTo(doc.page.width - 48, 218).strokeColor('#E2E8F0').stroke();

  labelValue(doc, 48, 236, 'Patient', data.patient.name);
  labelValue(doc, 300, 236, 'Appointment', data.appointment.number);
  labelValue(doc, 48, 276, 'Age / Gender', `${data.patient.age ?? '-'} / ${data.patient.gender ?? '-'}`);
  labelValue(doc, 300, 276, 'Date', data.appointment.date);
  labelValue(doc, 48, 316, 'Phone', data.patient.phone ?? '-');
  labelValue(doc, 300, 316, 'Follow up', data.followUpDate ?? 'Not scheduled');

  doc.moveTo(48, 362).lineTo(doc.page.width - 48, 362).strokeColor('#E2E8F0').stroke();
  doc.fontSize(9).font('Helvetica-Bold').fillColor('#0B5FFF').text('DIAGNOSIS', 48, 378);
  doc.fontSize(11).font('Helvetica').fillColor('#0F172A').text(data.diagnosis, 48, 394, { width: doc.page.width - 96 });

  let y = Math.max(doc.y + 24, 440);
  doc.fontSize(9).font('Helvetica-Bold').fillColor('#0B5FFF').text('MEDICATION', 48, y);
  y += 20;
  doc.rect(48, y, doc.page.width - 96, 24).fill('#F1F5F9');
  doc.fillColor('#334155').fontSize(8).font('Helvetica-Bold');
  doc.text('MEDICINE', 56, y + 8);
  doc.text('DOSAGE', 250, y + 8);
  doc.text('FREQUENCY', 340, y + 8);
  doc.text('DURATION', 440, y + 8);
  y += 28;

  for (const item of data.items) {
    doc.fillColor('#0F172A').fontSize(9).font('Helvetica-Bold').text(item.medicineName, 56, y, { width: 185 });
    doc.font('Helvetica').fontSize(9).text(item.dosage, 250, y, { width: 85 });
    doc.text(item.frequency, 340, y, { width: 95 });
    doc.text(item.duration, 440, y, { width: 100 });
    if (item.instructions) {
      doc.fontSize(8).fillColor('#64748B').text(item.instructions, 56, y + 14, { width: doc.page.width - 112 });
      y += 18;
    }
    y += 26;
    if (y > doc.page.height - 180) {
      doc.addPage();
      y = 60;
    }
  }

  const notesY = Math.max(y + 16, 620);
  doc.fontSize(9).font('Helvetica-Bold').fillColor('#0B5FFF').text('NOTES', 48, notesY);
  doc.fontSize(10).font('Helvetica').fillColor('#0F172A').text(data.notes || 'No additional notes.', 48, notesY + 16, { width: doc.page.width - 96 });

  doc.fontSize(8).fillColor('#94A3B8').text(
    'This prescription is digitally generated by MediBook. Please follow the prescribed dosage. Contact the clinic in case of adverse reactions.',
    48,
    doc.page.height - 72,
    { width: doc.page.width - 96, align: 'center' },
  );

  return toBuffer(doc);
}

interface InvoicePdfData {
  invoiceNumber: string;
  paymentId: string;
  paidAt: Date | null;
  provider: string;
  method: string;
  appointmentNumber: string;
  appointmentDate: string;
  patient: { name: string; email: string; phone?: string | null };
  doctor: { name: string; qualification: string };
  clinic?: { name: string; address: string } | null;
  consultationFee: number;
  amountPaid: number;
  currency: string;
}

export async function renderInvoicePdf(data: InvoicePdfData): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'A4', margin: 48, info: { Title: `Invoice ${data.invoiceNumber}` } });
  drawHeader(doc, 'INVOICE', `Invoice No: ${data.invoiceNumber}`);

  doc.y = 120;
  labelValue(doc, 48, 120, 'Billed to', data.patient.name);
  labelValue(doc, 48, 160, 'Email', data.patient.email);
  labelValue(doc, 48, 200, 'Phone', data.patient.phone ?? '-');
  labelValue(doc, 300, 120, 'Payment reference', data.paymentId);
  labelValue(doc, 300, 160, 'Paid on', data.paidAt ? data.paidAt.toISOString().slice(0, 10) : 'Pending');
  labelValue(doc, 300, 200, 'Method', data.method);

  doc.moveTo(48, 258).lineTo(doc.page.width - 48, 258).strokeColor('#E2E8F0').stroke();
  doc.fontSize(9).font('Helvetica-Bold').fillColor('#0B5FFF').text('APPOINTMENT DETAILS', 48, 276);
  doc.fontSize(10).font('Helvetica').fillColor('#0F172A');
  doc.text(`Appointment ${data.appointmentNumber}`, 48, 296);
  doc.text(`${data.doctor.name} · ${data.doctor.qualification}`, 48, 314);
  doc.text(`${data.appointmentDate}`, 48, 332);
  if (data.clinic) doc.text(`${data.clinic.name}, ${data.clinic.address}`, 48, 350, { width: doc.page.width - 96 });

  const tableY = 400;
  doc.rect(48, tableY, doc.page.width - 96, 28).fill('#F1F5F9');
  doc.fillColor('#334155').fontSize(9).font('Helvetica-Bold');
  doc.text('DESCRIPTION', 60, tableY + 9);
  doc.text('AMOUNT', doc.page.width - 160, tableY + 9, { width: 100, align: 'right' });

  doc.fillColor('#0F172A').font('Helvetica').fontSize(10);
  doc.text('Doctor consultation', 60, tableY + 48);
  doc.text(`${data.currency} ${data.consultationFee.toFixed(2)}`, doc.page.width - 160, tableY + 48, {
    width: 100,
    align: 'right',
  });

  doc.moveTo(48, tableY + 80).lineTo(doc.page.width - 48, tableY + 80).strokeColor('#E2E8F0').stroke();
  doc.font('Helvetica-Bold').fontSize(12);
  doc.text('Total paid', doc.page.width - 260, tableY + 96, { width: 140, align: 'right' });
  doc.text(`${data.currency} ${data.amountPaid.toFixed(2)}`, doc.page.width - 160, tableY + 96, {
    width: 100,
    align: 'right',
  });

  doc.fontSize(8).font('Helvetica').fillColor('#94A3B8').text(
    'This is a computer-generated invoice. For billing queries contact support@medibook.in.',
    48,
    doc.page.height - 72,
    { width: doc.page.width - 96, align: 'center' },
  );

  return toBuffer(doc);
}
